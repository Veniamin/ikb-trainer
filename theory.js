window.pyRef = (tid) => {
  const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
  const rows = (window.PYREF[tid] || []).map((r) =>
    typeof r === "string"
      ? `<tr><th colspan="3">${r}</th></tr>`
      : `<tr><td><code>${esc(r[0])}</code></td><td>${r[1]}</td><td>${r[2] ? `<code>${esc(r[2])}</code>` : ""}</td></tr>`
  );
  return `<div class="scroll"><table class="mini pyref">${rows.join("")}</table></div>`;
};
